#include <fmt/core.h>
#include <fstream>

#include "build/manager.hpp"
#include "fmt/ranges.h"
#include "logger.hpp"
#include "rustify.hpp"

namespace muuk::build {

    Result<void> generate_cmake_toolchain_file(
        const BuildProfile& profile,
        const std::string& profile_name,
        const std::filesystem::path& output_path) {
        std::ofstream out(output_path);
        if (!out.is_open()) {
            return Err(fmt::format("Failed to open output file '{}'", output_path.string()));
        }

        muuk::logger::info("Generating CMake toolchain file for profile '{}' at '{}'", profile_name, output_path.string());

        // Join flag vectors into single strings
        const auto join_flags = [](const std::vector<std::string>& vec) -> std::string {
            return fmt::format("{}", fmt::join(vec, " "));
        };

        const std::string cflags = join_flags(profile.cflags);
        const std::string aflags = join_flags(profile.aflags);
        const std::string lflags = join_flags(profile.lflags);
        const std::string defines = join_flags(profile.defines);

        // --- Write the CMake file content
        const std::string content = fmt::format(R"(# ----------------------------------------------------------
# Toolchain for Muuk build profile: {0}
# Generated by muuk::build
# ----------------------------------------------------------

set(CMAKE_GENERATOR "Ninja" CACHE STRING "Default generator" FORCE)

# Compiler setup
set(CMAKE_C_COMPILER gcc CACHE STRING "C compiler")
set(CMAKE_CXX_COMPILER g++ CACHE STRING "C++ compiler")

# --- Custom Build Type: Muuk
set(CMAKE_CONFIGURATION_TYPES "Muuk" CACHE STRING "Supported build types" FORCE)
set(CMAKE_BUILD_TYPE "Muuk" CACHE STRING "Current build type" FORCE)

# --- Flags for Muuk build type
set(CMAKE_C_FLAGS_MUUK "{1}" CACHE STRING "C flags for Muuk" FORCE)
set(CMAKE_CXX_FLAGS_MUUK "{1}" CACHE STRING "C++ flags for Muuk" FORCE)
set(CMAKE_EXE_LINKER_FLAGS_MUUK "{2}" CACHE STRING "Linker flags for Muuk" FORCE)
set(CMAKE_STATIC_LINKER_FLAGS_MUUK "{3}" CACHE STRING "Archiver flags for Muuk" FORCE)

# --- Apply these flags globally for simplicity (optional)
set(CMAKE_C_FLAGS "${{CMAKE_C_FLAGS_MUUK}}" CACHE STRING "C flags" FORCE)
set(CMAKE_CXX_FLAGS "${{CMAKE_CXX_FLAGS_MUUK}}" CACHE STRING "C++ flags" FORCE)
set(CMAKE_EXE_LINKER_FLAGS "${{CMAKE_EXE_LINKER_FLAGS_MUUK}}" CACHE STRING "Linker flags" FORCE)
set(CMAKE_STATIC_LINKER_FLAGS "${{CMAKE_STATIC_LINKER_FLAGS_MUUK}}" CACHE STRING "Archiver flags" FORCE)

# --- Defines
add_compile_definitions({4})

# --- Output directories (relative to the build directory)
set(CMAKE_RUNTIME_OUTPUT_DIRECTORY "${{CMAKE_BINARY_DIR}}/bin" CACHE PATH "Executable output dir" FORCE)
set(CMAKE_LIBRARY_OUTPUT_DIRECTORY "${{CMAKE_BINARY_DIR}}/lib" CACHE PATH "Shared library output dir" FORCE)
set(CMAKE_ARCHIVE_OUTPUT_DIRECTORY "${{CMAKE_BINARY_DIR}}/lib" CACHE PATH "Static library output dir" FORCE)
)",
                                                profile_name, // {0}
                                                cflags, // {1}
                                                lflags, // {2}
                                                aflags, // {3}
                                                defines // {4}
        );

        out << content;
        out.close();

        muuk::logger::info("CMake toolchain file successfully generated: '{}'", output_path.string());
        return {};
    }

} // namespace muuk::build
